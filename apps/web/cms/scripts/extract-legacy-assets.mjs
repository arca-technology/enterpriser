import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import { UserRound, UsersRound, Building2, MessagesSquare, BriefcaseBusiness, Package, ListChecks, Logs, CircleHelp, Database, Wrench, Globe, History, GitBranch, Target, Flag, Folder, Mail, Workflow, FileText, Table2, EllipsisVertical, ChevronRight, ChevronLeft, ChartNoAxesGantt, SlidersHorizontal, Zap, ZoomIn, ZoomOut, Scan, Maximize, MoveHorizontal, MoveVertical } from "lucide";
import { faFacebook, faInstagram, faLinkedin, faReddit, faTiktok, faYoutube, faWhatsapp } from "@fortawesome/free-brands-svg-icons";
import { Network, CircleDot, List } from "lucide";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const html = await readFile(path.join(root, "index.html"), "utf8");
const { version } = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
const configSource = await readFile(path.join(root, "config.js"), "utf8");
const styles = html.match(/<style>([\s\S]*?)<\/style>/)?.[1];
const body = html.match(/<body>([\s\S]*?)<script src="config\.js"><\/script>/)?.[1];

if (!styles || !body) {
  throw new Error("Nao foi possivel extrair o CSS ou o corpo do CRM legado.");
}

const markup = body.replace(/\s*<script src="app\.js"><\/script>\s*<\/body>[\s\S]*$/, "").trim();
const notice = "/* Gerado por npm run sync:legacy a partir de index.html. */\n";
const sandbox = { window: {} };
vm.runInNewContext(configSource, sandbox, { filename: "config.js" });

if (!sandbox.window.CRM_CONFIG) {
  throw new Error("Nao foi possivel extrair a configuracao do CRM.");
}

await mkdir(path.join(root, "public", "legacy"), { recursive: true });
for (const directory of [path.join(root, "vendor"), path.join(root, "public", "legacy", "vendor")]) {
  await mkdir(directory, { recursive: true });
  for (const file of ["dagre.min.js", "dagre.min.js.LEGAL.txt"]) await copyFile(path.join(root, "node_modules", "@dagrejs", "dagre", "dist", file), path.join(directory, file));
  await copyFile(path.join(root, "node_modules", "d3-hierarchy", "dist", "d3-hierarchy.min.js"), path.join(directory, "d3-hierarchy.min.js"));
  await copyFile(path.join(root, "node_modules", "d3-hierarchy", "LICENSE"), path.join(directory, "d3-hierarchy.LICENSE"));
}
const iconNodes = { contacts: UsersRound, companies: Building2, conversations: MessagesSquare, deals: BriefcaseBusiness, projects: Package, activities: ListChecks,
  log: Logs, help: CircleHelp, registrations: Database, tools: Wrench, social: Globe, updates: History,
  products: Package, pipelines: GitBranch, users: UsersRound, goals: Target, objectives: Flag,
  files: Folder, emails: Mail, processes: Workflow, documents: FileText, tables: Table2, cms: BriefcaseBusiness, more: EllipsisVertical, chevronRight: ChevronRight,
  chevronLeft: ChevronLeft, timeline: ChartNoAxesGantt, filter: SlidersHorizontal, person: UserRound, automation: Zap, sms: MessagesSquare,
  mapOrganogram: Network, mapRadial: CircleDot, list: List,
  flow: Workflow, flowZoomIn: ZoomIn, flowZoomOut: ZoomOut, flowFit: Scan, flowFullscreen: Maximize, flowHorizontal: MoveHorizontal, flowVertical: MoveVertical };
const escapeAttribute = (value) => String(value).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const navigationIcons = Object.fromEntries(Object.entries(iconNodes).map(([key, nodes]) => [key,
  `<svg viewBox="0 0 24 24" aria-hidden="true">${nodes.map(([tag, attributes]) => `<${tag} ${Object.entries(attributes).map(([name, value]) => `${name}="${escapeAttribute(value)}"`).join(" ")}/>`).join("")}</svg>`
]));
for (const [key, definition] of Object.entries({ facebook: faFacebook, instagram: faInstagram, linkedin: faLinkedin, reddit: faReddit, tiktokshop: faTiktok, youtube: faYoutube, whatsapp: faWhatsapp })) {
  const [width, height, , , paths] = definition.icon;
  navigationIcons[key] = `<svg class="brand-icon" viewBox="0 0 ${width} ${height}" aria-hidden="true">${[paths].flat().map((data) => `<path d="${escapeAttribute(data)}"/>`).join("")}</svg>`;
}
await writeFile(path.join(root, "public", "legacy", "navigation-icons.js"), `/* Lucide icons, ISC license. Generated by sync:legacy. */\nwindow.CRM_APP_VERSION = ${JSON.stringify(version)};\nwindow.CRM_NAV_ICONS = ${JSON.stringify(navigationIcons)};\n`);
await copyFile(path.join(root, "node_modules", "lucide", "LICENSE"), path.join(root, "public", "legacy", "navigation-icons.LICENSE"));
await copyFile(path.join(root, "node_modules", "@fortawesome", "free-brands-svg-icons", "LICENSE.txt"), path.join(root, "public", "legacy", "brand-icons.LICENSE"));
await writeFile(
  path.join(root, "app", "globals.css"),
  `${notice}${styles.trim()}\n\n#legacy-root { display: contents; }\n`,
);
await writeFile(
  path.join(root, "components", "legacy-markup.ts"),
  `/* Gerado por npm run sync:legacy a partir de index.html. */\nexport const legacyMarkup = ${JSON.stringify(markup)};\n`,
);
await writeFile(
  path.join(root, "components", "legacy-config.ts"),
  `/* Gerado por npm run sync:legacy a partir de config.js. */\nexport const legacyConfig = ${JSON.stringify(sandbox.window.CRM_CONFIG, null, 2)} as const;\n`,
);
await copyFile(path.join(root, "app.js"), path.join(root, "public", "legacy", "app.js"));
await copyFile(path.join(root, "config.js"), path.join(root, "public", "legacy", "config.js"));
await copyFile(path.join(root, "privacy-policy.html"), path.join(root, "public", "privacy-policy.html"));
