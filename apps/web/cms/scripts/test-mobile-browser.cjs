const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { chromium } = require('playwright');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8').replace(/<script[^>]*>[\s\S]*?<\/script>/g, '');
const source = fs.readFileSync(path.join(root, 'app.js'), 'utf8').replace(/^startApp\(\);/m, '');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.route('**/*', (route) => route.request().url() === 'http://mobile-test.local/' ? route.fulfill({ contentType: 'text/html', body: html }) : route.abort());
    await page.goto('http://mobile-test.local/');
    await page.evaluate(() => { window.CRM_CONFIG = {}; });
    await page.addScriptTag({ content: fs.readFileSync(path.join(root, 'public/legacy/navigation-icons.js'), 'utf8') });
    await page.addScriptTag({ content: source });
    await page.evaluate(async () => { await loadAll(); document.getElementById('boot-gate')?.remove(); hideLogin(); saveNavigationPreference({ mode: 'sidebar' }); state.tab = 'contacts'; cache.contacts[0].name = 'Pessoa com um nome completo muito longo para conferir a leitura no celular'; render(); });
    for (const width of [360, 390, 430]) {
      await page.setViewportSize({ width, height: 844 });
      assert.equal(await page.locator('#app-sidebar').isVisible(), false);
      assert.equal(await page.locator('#main').evaluate((el) => el.getBoundingClientRect().left), 0);
      assert.equal(await page.locator('#mobile-navigation').isVisible(), true);
      assert.equal(await page.locator('#new').isVisible(), true);
      assert.equal(await page.locator('#mobile-filter-btn').isVisible(), true);
      assert.equal(await page.locator('#main table thead').isVisible(), false);
      assert.equal(await page.locator('#main .mobile-record-title').first().evaluate((el) => getComputedStyle(el).whiteSpace), 'normal');
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await page.screenshot({ path: path.join(os.tmpdir(), `mobile-list-${width}.png`) });
    }
    await page.evaluate(() => setTheme(true));
    assert.equal(await page.locator('#mobile-navigation').evaluate((el) => el.getBoundingClientRect().bottom), 844);
    assert.equal(await page.locator('#mobile-navigation').isVisible(), true);
    await page.screenshot({ path: path.join(os.tmpdir(), 'mobile-list-light.png') });
    await page.locator('#mobile-presentation').click();
    assert.equal(await page.locator('#main table thead').isVisible(), true);
    assert.equal(await page.evaluate(() => localStorage.getItem('crm_mobile_presentation')), 'table');
    await page.locator('#mobile-presentation').click();
    await page.locator('#search').fill('Nenhum resultado para esta busca');
    assert.equal(await page.locator('#main .mobile-record-row').count(), 0);
    await page.locator('#search').fill('');
    await page.locator('#mobile-filter-btn').click();
    await page.locator('[data-mobile-filter="name"]').click();
    assert.equal(await page.locator('#filter-dd').isVisible(), true);
    await page.evaluate(() => closeFloaters());
    await page.locator('#mobile-more').click();
    assert.equal(await page.locator('#mobile-navigation-menu').evaluate((el) => el.open), true);
    await page.locator('#mobile-navigation-menu .mobile-menu-item').filter({ hasText: /^Empresas$/ }).click();
    await page.waitForFunction(() => state.tab === 'companies');
    assert.equal(await page.locator('#mobile-navigation-menu').count(), 0);
    await page.locator('[data-mobile-tab="contacts"]').click();
    await page.locator('#main .record-primary-cell').first().click();
    assert.equal(await page.locator('#modal-root .modal').count(), 1);
    await page.keyboard.press('Escape');
    await page.locator('#mobile-more').click();
    await page.locator('#mobile-navigation-menu summary').filter({ hasText: 'Cadastros' }).click();
    await page.locator('#mobile-navigation-menu details .mobile-menu-item').filter({ hasText: /^Produtos$/ }).click();
    assert.equal(await page.locator('#registrations-root').count(), 1);
    assert.equal(await page.locator('.sidebar-module-overlay').evaluate((el) => el.getBoundingClientRect().left), 0);
    await page.keyboard.press('Escape');
    await page.setViewportSize({ width: 1440, height: 900 });
    assert.equal(await page.locator('#mobile-navigation').isVisible(), false);
    assert.equal(await page.locator('#app-sidebar').isVisible(), true);
    assert.equal(await page.locator('#main table thead').isVisible(), true);
    assert.equal(await page.locator('#app-sidebar').evaluate((el) => el.getBoundingClientRect().width), 64);
    assert.deepEqual(errors, []);
    console.log('Mobile lists, full-width navigation, touch controls, table preference, filters, actions, submodules and unchanged desktop passed.');
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
