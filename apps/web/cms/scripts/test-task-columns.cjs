const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const code = source.slice(source.indexOf('const TASK_COLUMN_ORDER ='), source.indexOf('function orderedColumns('));
const context = vm.createContext({});
vm.runInContext(code, context);
const definitions = ['Origem', 'Tarefa', 'Prioridade', 'Status', 'Cliente', 'Produto', 'Responsáveis padrão', 'Prazo', 'Requer no Setup', 'Comentários'].map((h, i) => ({ h, k: `c${i}` }));
const labels = (cols) => Array.from(cols, (col) => context.taskColumnLabel(col.h));
assert.deepEqual(labels(context.taskColumnOrder(definitions)).slice(0, 5), ['CLIENTE', 'PRODUTO', 'TAREFA', 'STATUS', 'ORIGEM']);
assert.deepEqual(labels(context.taskColumnOrder(definitions, ['c9', 'c3', 'c1', 'c5', 'c4'])).slice(0, 5), ['CLIENTE', 'PRODUTO', 'TAREFA', 'STATUS', 'COMENTÁRIOS']);
const registration = definitions.filter((col) => col.h !== 'Cliente');
assert.deepEqual(labels(context.taskColumnOrder(registration)).slice(0, 3), ['PRODUTO', 'TAREFA', 'STATUS']);
const prefs = {};
context.applyTaskPreset(definitions, prefs, 'resumo');
assert.equal(prefs.c1, true);
assert.equal(prefs.c3, true);
assert.equal(prefs.c6, true);
assert.equal(prefs.c8, false);
context.applyTaskPreset(definitions, prefs, 'classificacao');
assert.equal(prefs.c8, true);
assert.equal(prefs.c6, false);
context.applyTaskPreset(definitions, prefs, 'completo');
assert(definitions.every((col) => prefs[col.k]));
const cells = Object.fromEntries(definitions.map((col) => [col.k, { classList: { add() {} }, style: {} }]));
const table = { classList: { add() {} }, querySelectorAll: (selector) => [cells[selector.match(/="([^"]+)"/)[1]]] };
context.styleTaskFrozenColumns(table, 'data-k', definitions);
assert.equal(cells.c4.style.left, '72px');
assert.equal(cells.c4.style.width, '105px');
assert.equal(cells.c5.style.width, '70px');
assert.equal(cells.c5.style.left, '177px');
assert.equal(cells.c1.style.left, '247px');
assert.equal(cells.c1.style.width, '240px');
assert.equal(cells.c3.style.left, '487px');
assert.equal(cells.c3.style.width, '97.5px');
context.styleTaskFrozenColumns(table, 'data-k', registration, true);
assert.equal(cells.c5.style.left, '72px');
assert.equal(cells.c1.style.left, '142px');
assert.equal(cells.c3.style.left, '382px');
console.log('Task column defaults, locked order, presets and sticky widths passed.');
