const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const context = vm.createContext({ cache: { productById: {}, projectById: {}, productActivities: [] }, loadProjectTasks: () => [] });
const setup = source.slice(source.indexOf('const DELIVERY_CHANNEL_OPTIONS ='), source.indexOf('const MAX_PIPELINES ='));
vm.runInContext(setup + source.match(/function normalizeTextList\([^]*?^}/m)[0], context);
const task = { channel: 'BLING', required_setup: ['BLING', 'SHEIN'] };
assert.equal(context.projectTaskEnabled({ erp_platform: 'BLING' }, task), false);
assert.equal(context.projectTaskEnabled({ marketplace_channels: ['SHEIN'] }, task), false);
assert.equal(context.projectTaskEnabled({ erp_platform: 'BLING', marketplace_channels: ['SHEIN'] }, task), true);
assert.equal(context.projectTaskEnabled({}, { channel: 'BLING', required_setup: [] }), true);
assert.equal(context.projectTaskEnabled({}, { channel: 'BLING' }), false);
assert.equal(context.projectTaskEnabled({ marketplace_channels: ['TIKTOKSHOP'] }, { required_setup: ['TikTok Shop'] }), true);
assert.equal(context.projectTaskEnabled({ marketplace_channels: ['MERCADO LIVRE'] }, { required_setup: ['MERCADO PAGO', 'MERCADO ENVIOS'] }), true);
assert.equal(context.projectTaskEnabled({ company_setup: 'ABERTA' }, { required_setup: ['ABERTA'] }), true);
vm.runInContext(source.match(/function operationalProjectTasks\([^]*?^}/m)[0], context);
context.cache.projectById.p = { erp_platform: 'BLING' };
context.cache.productActivities = [{ id: 'template', ...task }];
context.loadProjectTasks = () => [{ id: 'existing', project_id: 'p', source_template_id: 'template', channel: 'BLING', required_setup: ['BLING'] }];
assert.equal(context.operationalProjectTasks('p').length, 0, 'An existing task must follow updated template requirements');
context.cache.projectById.p.marketplace_channels = ['SHEIN'];
assert.equal(context.operationalProjectTasks('p').length, 1);
console.log('Task setup requirements checks passed.');
